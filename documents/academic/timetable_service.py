DAY_INDEX_MAP = {
    'monday': 1,
    'tuesday': 2,
    'wednesday': 3,
    'thursday': 4,
    'friday': 5,
    'saturday': 6,
    'sunday': 7,
}

DAYS_ORDER = ['Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday']


def compute_free_slots(weekly_schedule: List[Dict[str, Any]], start_hour: int = 8, end_hour: int = 17) -> List[Dict[str, Any]]:
    """
    Compute gaps/free study slots between start_hour (default 08:00) and end_hour (default 17:00)
    for each weekday (Monday to Friday).
    """
    free_slots = []
    
    # Group schedule by day
    schedule_by_day: Dict[str, List[Dict[str, Any]]] = {day: [] for day in DAYS_ORDER}
    for slot in weekly_schedule:
        day = slot.get('day', '').capitalize()
        if day in schedule_by_day:
            schedule_by_day[day].append(slot)

    for day in DAYS_ORDER:
        day_slots = schedule_by_day[day]
        day_index = DAY_INDEX_MAP.get(day.lower(), 1)
        
        # Sort slots by start_time
        parsed_slots = []
        for s in day_slots:
            try:
                st = datetime.strptime(s.get('start_time', '08:00'), '%H:%M').time()
                et = datetime.strptime(s.get('end_time', '09:00'), '%H:%M').time()
                parsed_slots.append((st, et))
            except Exception:
                continue
        parsed_slots.sort(key=lambda x: x[0])

        current_time = datetime.strptime(f"{start_hour:02d}:00", '%H:%M').time()
        end_boundary = datetime.strptime(f"{end_hour:02d}:00", '%H:%M').time()

        for st, et in parsed_slots:
            if et <= current_time or st >= end_boundary:
                continue
            st = max(st, current_time)
            et = min(et, end_boundary)
            if st > current_time:
                # Found free interval
                diff_minutes = (datetime.combine(datetime.min, st) - datetime.combine(datetime.min, current_time)).total_seconds() / 60
                if diff_minutes >= 45:  # At least 45 minutes gap
                    duration_hrs = round(diff_minutes / 60.0, 1)
                    free_slots.append({
                        'day': day,
                        'day_index': day_index,
                        'start_time': current_time.strftime('%H:%M'),
                        'end_time': st.strftime('%H:%M'),
                        'duration_hours': duration_hrs,
                    })
            if et > current_time:
                current_time = et

        if current_time < end_boundary:
            diff_minutes = (datetime.combine(datetime.min, end_boundary) - datetime.combine(datetime.min, current_time)).total_seconds() / 60
            if diff_minutes >= 45:
                duration_hrs = round(diff_minutes / 60.0, 1)
                free_slots.append({
                    'day': day,
                    'day_index': day_index,
                    'start_time': current_time.strftime('%H:%M'),
                    'end_time': end_boundary.strftime('%H:%M'),
                    'duration_hours': duration_hrs,
                })

    return free_slots


def is_starter_schedule(schedule_data):
    """Recognize the exact synthetic schedule generated by the old fallback."""
    if not isinstance(schedule_data, dict):
        return False
    slots = schedule_data.get('weekly_schedule', [])
    if not isinstance(slots, list) or not all(isinstance(slot, dict) for slot in slots):
        return False
    return len(slots) == 3 and {s.get('id') for s in slots} == {
        'mon_0800_session1', 'wed_1000_session2', 'fri_1400_session3',
    } and {s.get('unit_code') for s in slots} == {'LEC 101', 'LEC 102', 'PRA 103'}


def validate_schedule_data(schedule_data):
    if not isinstance(schedule_data, dict) or is_starter_schedule(schedule_data):
        raise ValueError('A verified timetable is required.')
    slots = schedule_data.get('weekly_schedule')
    if not isinstance(slots, list) or not slots:
        raise ValueError('No readable timetable classes were found.')
    for slot in slots:
        if not isinstance(slot, dict) or str(slot.get('day', '')).lower() not in DAY_INDEX_MAP:
            raise ValueError('Invalid timetable day.')
        start = datetime.strptime(slot.get('start_time', ''), '%H:%M').time()
        end = datetime.strptime(slot.get('end_time', ''), '%H:%M').time()
        if start >= end or not (slot.get('unit_code') or slot.get('unit_name')):
            raise ValueError('Each class needs a unit and a valid start and end time.')
    result = dict(schedule_data)
    result['free_slots'] = compute_free_slots(slots)
    return result


class TimetableExtractionService:
    """
    Multimodal Vision and OCR extraction service for academic timetables.
    """

    @classmethod
    def extract_from_image(
        cls,
        image_bytes: bytes,
        mime_type: str = "image/jpeg",
        programme_name: str = "",
        level_name: str = "",
        institution_name: str = "",
    ) -> Dict[str, Any]:
        """
        Process the timetable image through the AI Gateway vision chain and
        construct the canonical schedule JSON.

        Candidates come from ``TIMETABLE_OCR_FALLBACK_CHAIN`` (fast cloud OCR
        models first, local Ollama last). ``TIMETABLE_OCR_PROVIDER`` can pin a
        single provider; ``auto`` walks the whole chain. Each rung is tried in
        order until one returns parseable schedule JSON.
        """
        from pwanimate.ai.gateway import AIGateway, ChatMessage, LLMRequest
        from pwanimate.ai.gateway.types import AttachmentData

        prompt = cls._build_extraction_prompt(programme_name, level_name, institution_name)
        image = AttachmentData(
            id="timetable-source",
            name="timetable",
            mime_type=mime_type or "image/jpeg",
            attachment_type="image",
            data_bytes=image_bytes,
        )

        gateway = AIGateway()
        last_error: Optional[Exception] = None
        for candidate in cls._resolve_ocr_chain():
            provider_name = candidate.get("provider")
            model_name = candidate.get("model")
            label = f"{provider_name}:{model_name}" if model_name else str(provider_name)
            try:
                result = gateway.generate(LLMRequest(
                    task="timetable_vision_extraction",
                    messages=[ChatMessage(role="user", content=prompt, attachments=[image])],
                    provider=provider_name,
                    model=model_name,
                    temperature=0.1,
                    max_tokens=4096,
                    attachments=[image],
                    metadata={
                        "required_capability": "image",
                        "fallback_chain": [candidate],
                    },
                ))
            except Exception as exc:  # noqa: BLE001 - a dead rung must not stop the chain
                last_error = exc
                logger.warning("[TIMETABLE-EXTRACT] Candidate %s failed: %s", label, exc)
                continue

            extracted = cls._parse_schedule_json(result.content or "")
            if isinstance(extracted, dict) and extracted.get('weekly_schedule'):
                # Augment with computed free slots, stable slot ids, unit catalogue name enrichment, and venue sanitization
                from documents.academic.models import AcademicUnit
                weekly_schedule = extracted['weekly_schedule']
                unit_cache = {
                    u.code.upper().replace(' ', ''): u.name
                    for u in AcademicUnit.objects.filter(is_active=True).only('code', 'name')
                }
                for slot in weekly_schedule:
                    d = str(slot.get('day', '')).capitalize()
                    slot['day'] = d
                    slot['day_index'] = DAY_INDEX_MAP.get(d.lower(), 1)

                    code = str(slot.get('unit_code', '')).strip()
                    code_norm = code.upper().replace(' ', '')
                    venue = str(slot.get('venue', '')).strip()
                    venue_norm = venue.upper().replace(' ', '')

                    # Never allow a unit code to be stored as the venue
                    if venue_norm == code_norm or venue_norm in unit_cache:
                        slot['venue'] = ''

                    # Auto-enrich unit_name from catalogue if missing or if cohort text was extracted as name
                    cur_name = str(slot.get('unit_name') or '').strip()
                    if not cur_name or 'bsc' in cur_name.lower() or 'bed' in cur_name.lower() or len(cur_name) < 3:
                        if code_norm in unit_cache:
                            slot['unit_name'] = unit_cache[code_norm]

                    if not slot.get('id'):
                        raw_id = f"{d[:3].lower()}_{slot.get('start_time', '00').replace(':', '')}_{code.replace(' ', '').lower()}"
                        slot['id'] = re.sub(r'[^a-zA-Z0-9_]', '', raw_id)

                extracted['free_slots'] = compute_free_slots(weekly_schedule)
                logger.info(
                    "[TIMETABLE-EXTRACT] Candidate %s produced %d slots.",
                    label, len(weekly_schedule),
                )
                return extracted

            last_error = ValueError(f"Candidate {label} returned no readable timetable classes.")
            logger.warning("[TIMETABLE-EXTRACT] %s", last_error)

        detail = f" Last error: {last_error}" if last_error else ""
        raise ValueError(
            'Timetable extraction is unavailable or no readable classes were found. '
            f'Please retry or enter the schedule manually.{detail}'
        )

    @staticmethod
    def _resolve_ocr_chain() -> List[Dict[str, Any]]:
        """Ordered (provider, model) rungs for timetable extraction."""
        chain = [
            {"provider": str(c.get("provider") or "").strip().lower(), "model": c.get("model")}
            for c in (getattr(settings, "TIMETABLE_OCR_FALLBACK_CHAIN", None) or [])
            if isinstance(c, dict) and c.get("provider")
        ]
        provider_pin = (getattr(settings, "TIMETABLE_OCR_PROVIDER", "auto") or "auto").strip().lower()
        if provider_pin not in ("", "auto", "chain"):
            pinned = [c for c in chain if c["provider"] == provider_pin]
            chain = pinned or [{
                "provider": provider_pin,
                "model": getattr(settings, "TIMETABLE_OCR_MODEL", None),
            }]
        seen = set()
        unique = []
        for c in chain:
            key = (c["provider"], str(c.get("model") or "").strip().lower())
            if key not in seen:
                seen.add(key)
                unique.append(c)
        return unique

    @staticmethod
    def _parse_schedule_json(text: str) -> Optional[Dict[str, Any]]:
        """Tolerantly parse the model's JSON output (fences, prose, truncation)."""
        clean = (text or "").strip()
        if clean.startswith("```"):
            clean = re.sub(r"^```[a-zA-Z]*\n?", "", clean)
            clean = re.sub(r"\n?```$", "", clean)
        try:
            return json.loads(clean)
        except json.JSONDecodeError:
            pass
        start = clean.find("{")
        end = clean.rfind("}")
        if start != -1 and end > start:
            try:
                return json.loads(clean[start:end + 1])
            except json.JSONDecodeError:
                return None
        return None

    @staticmethod
    def _build_extraction_prompt(programme_name: str, level_name: str, institution_name: str) -> str:
        return f"""
You are an expert academic timetable vision parser. Analyze this timetable image for {programme_name} ({level_name}) at {institution_name}.
Extract every lecture, lab, practical, seminar, or tutorial class slot into a clean, accurate JSON structure.

Grid Structure Understanding:
- Timetables often have DAYS as vertical rows (Monday, Tuesday, Wednesday, Thursday, Friday, Saturday) and TIME INTERVALS as horizontal column headers (e.g. "7am-9am", "9am-11am", "11am-1pm", "1pm-3pm", "3pm-5pm", "5pm-7pm"), or vice-versa.
- Cells containing "---" or blank dashes indicate NO session (skip them!). Only extract cells that actually contain a class.

Crucial Field Distinctions Inside Each Cell:
1. "unit_code": The actual course/unit code (e.g. "SMA B261", "SCS B204", "SCS B207", "SMA B203", "SCS B202", "SCS B209", "SMA B201", "CSC 221").
   - DO NOT confuse the student cohort/programme list (e.g. "Bsc Maths-Y2, Bsc Comp Sci-Y2, Bed Geog-Maths-Y2") with the unit code!
2. "session_type": "Lecture", "Lab", "Practical", "Tutorial", or "Seminar". If the cell says "Practicals" or "Lab", label it "Practical" or "Lab".
3. "lecturer": Locate the person/instructor name in the cell (e.g. "MR. JOSEPH MUTUA", "MR. P. ARNOLD", "MS. GRACE WAKESHO", "MR. MASOUD ATHMAN", "DR. R. ADENYA", "MR. AMRAN HASSAN").
4. "venue": The physical classroom, lecture hall, lab, or building code (e.g. "LTN", "LTW", "SBN 001", "LH1", "Lab B").
   - CRITICAL: NEVER use a unit code (e.g. "SMA B203") as the venue! If no venue is listed, use "".
5. "unit_name": Full title of the unit if visible, otherwise "".
6. "start_time" & "end_time": 24-hour "HH:MM" (e.g. "7am-9am" -> "07:00" to "09:00", "11am-1pm" -> "11:00" to "13:00", "1pm-3pm" -> "13:00" to "15:00", "3pm-5pm" -> "15:00" to "17:00", "5pm-7pm" -> "17:00" to "19:00").

Return ONLY valid JSON matching this schema:
{{
  "title": "{programme_name} Timetable",
  "weekly_schedule": [
    {{
      "id": "mon_1100_smab261",
      "day": "Monday",
      "day_index": 1,
      "start_time": "11:00",
      "end_time": "13:00",
      "unit_code": "SMA B261",
      "unit_name": "Probability and Statistics I",
      "venue": "LTN",
      "lecturer": "MR. JOSEPH MUTUA",
      "session_type": "Lecture"
    }}
  ]
}}
Output pure JSON with no markdown formatting.
"""



class ProgrammeTimetableManager:
    """Service facade for managing cohort timetables and Spark context delivery."""

    @staticmethod
    def get_active_timetable(
        institution: Optional[Institution],
        programme: Optional[Programme],
        academic_level: Optional[AcademicLevel],
        semester: Optional[Semester] = None,
        timetable_type: str = TimetableType.LECTURE,
        include_processing: bool = True,
        academic_year: Optional[AcademicYear] = None,
    ) -> Optional[ProgrammeTimetable]:
        """Fetch active (or currently processing) timetable for a specific student cohort."""
        from django.db.models import Q
        if not programme or not academic_level:
            return None

        # Include PROCESSING so the dashboard panel shows the Spark AI shimmer animation and HTMX auto-poll
        status_q = Q(is_active=True, status=TimetableStatus.ACTIVE)
        if include_processing:
            status_q |= Q(status=TimetableStatus.PROCESSING)

        qs = ProgrammeTimetable.objects.filter(
            status_q,
            programme=programme,
            academic_level=academic_level,
            timetable_type=timetable_type,
        )

        if institution:
            qs = qs.filter(Q(institution=institution) | Q(institution__isnull=True))
        if academic_year:
            qs = qs.filter(Q(academic_year=academic_year) | Q(academic_year__isnull=True))
        if semester:
            exact = qs.filter(semester=semester)
            qs = exact if exact.exists() else qs.filter(semester__isnull=True)

        return next((tt for tt in qs.order_by('-revision_number', '-created_at')
                     if not is_starter_schedule(tt.schedule_data)), None)

    @staticmethod
    @transaction.atomic
    def activate_timetable(timetable, schedule_data):
        schedule_data = validate_schedule_data(schedule_data)
        Programme.objects.select_for_update().get(pk=timetable.programme_id)
        peers = ProgrammeTimetable.objects.filter(
            institution_id=timetable.institution_id, programme_id=timetable.programme_id,
            academic_level_id=timetable.academic_level_id,
            semester_id=timetable.semester_id, academic_year_id=timetable.academic_year_id,
            timetable_type=timetable.timetable_type, is_active=True,
        ).exclude(pk=timetable.pk)
        newer = peers.filter(revision_number__gt=timetable.revision_number).exists()
        if not newer:
            peers.update(is_active=False, status=TimetableStatus.SUPERSEDED)
        timetable.schedule_data = schedule_data
        timetable.raw_extracted_text = schedule_data.get('raw_text', '')
        timetable.is_active = not newer
        timetable.status = TimetableStatus.SUPERSEDED if newer else TimetableStatus.ACTIVE
        timetable.save(update_fields=['schedule_data', 'raw_extracted_text', 'is_active', 'status', 'updated_at'])
        return not newer

    @staticmethod
    @transaction.atomic
    def save_timetable_image(
        user,
        image_file,
        institution: Institution,
        programme: Programme,
        academic_level: AcademicLevel,
        semester: Optional[Semester] = None,
        academic_year: Optional[AcademicYear] = None,
        timetable_type: str = TimetableType.LECTURE,
        change_summary: str = "",
        custom_schedule: Optional[Dict[str, Any]] = None,
    ) -> ProgrammeTimetable:
        """
        Phase 1 (sync) — Persist the uploaded image and create a ProgrammeTimetable
        record with status=PROCESSING.  Returns immediately; the AI extraction is
        handled asynchronously by ``process_timetable_image_task``.

        If *custom_schedule* is provided (e.g. tests or manual entry) the schedule
        is stored straight away and the record is activated without a Celery task.
        """
        from documents.tasks.timetable import process_timetable_image_task

        # ── Revision number ───────────────────────────────────────────────────
        Programme.objects.select_for_update().get(pk=programme.pk)
        existing_rev = ProgrammeTimetable.objects.filter(
            institution=institution,
            programme=programme,
            academic_level=academic_level,
            timetable_type=timetable_type,
        ).order_by('-revision_number').first()

        new_rev_number = (existing_rev.revision_number + 1) if existing_rev else 1

        title = f"{programme.code} {academic_level.name} Timetable (Rev {new_rev_number})"

        # ── Shortcut: custom_schedule provided (no AI needed) ─────────────────
        if custom_schedule:
            schedule_data = custom_schedule
            if not schedule_data.get('free_slots'):
                schedule_data['free_slots'] = compute_free_slots(
                    schedule_data.get('weekly_schedule', [])
                )
            timetable = ProgrammeTimetable.objects.create(
                institution=institution,
                programme=programme,
                academic_level=academic_level,
                academic_year=academic_year or getattr(user, 'academic_year', None),
                semester=semester or getattr(user, 'semester', None),
                timetable_type=timetable_type,
                status=TimetableStatus.PROCESSING,
                revision_number=new_rev_number,
                title=title,
                change_summary=change_summary,
                source_image=image_file,
                schedule_data=schedule_data,
                is_active=True,
                uploaded_by=user,
            )
            ProgrammeTimetableManager.activate_timetable(timetable, schedule_data)
            logger.info(
                '[TIMETABLE] Custom-schedule timetable created (id=%s, rev=%s).',
                timetable.id, new_rev_number,
            )
            return timetable

        # ── Normal path: create PROCESSING record, fire Celery task ──────────
        timetable = ProgrammeTimetable.objects.create(
            institution=institution,
            programme=programme,
            academic_level=academic_level,
            academic_year=academic_year or getattr(user, 'academic_year', None),
            semester=semester or getattr(user, 'semester', None),
            timetable_type=timetable_type,
            status=TimetableStatus.PROCESSING,
            revision_number=new_rev_number,
            title=title,
            change_summary=change_summary,
            source_image=image_file,
            schedule_data={},           # populated by Celery task
            is_active=False,            # goes True once task completes
            uploaded_by=user,
        )

        logger.info(
            '[TIMETABLE] Record created (id=%s, rev=%s) — dispatching Celery task.',
            timetable.id, new_rev_number,
        )

        # Dispatch — countdowns allow the DB transaction to commit first
        transaction.on_commit(lambda: process_timetable_image_task.apply_async(
            args=[timetable.id], queue='docs_queue',
        ))

        return timetable

    @staticmethod
    @transaction.atomic
    def save_timetable_image_from_storage(
        user,
        storage_path: str,
        institution: Institution,
        programme: Programme,
        academic_level: AcademicLevel,
        semester: Optional[Semester] = None,
        academic_year: Optional[AcademicYear] = None,
        timetable_type: str = TimetableType.LECTURE,
        change_summary: str = "",
    ) -> ProgrammeTimetable:
        """Same as ``save_timetable_image`` but for an image that is already
        in object storage (uploaded straight to the bucket by the browser).

        The record is created in PROCESSING state and the AI extraction runs
        in the background, exactly like the classic upload path.
        """
        from documents.tasks.timetable import process_timetable_image_task

        Programme.objects.select_for_update().get(pk=programme.pk)
        existing_rev = ProgrammeTimetable.objects.filter(
            institution=institution,
            programme=programme,
            academic_level=academic_level,
            timetable_type=timetable_type,
        ).order_by('-revision_number').first()

        new_rev_number = (existing_rev.revision_number + 1) if existing_rev else 1

        title = f"{programme.code} {academic_level.name} Timetable (Rev {new_rev_number})"

        timetable = ProgrammeTimetable.objects.create(
            institution=institution,
            programme=programme,
            academic_level=academic_level,
            academic_year=academic_year or getattr(user, 'academic_year', None),
            semester=semester or getattr(user, 'semester', None),
            timetable_type=timetable_type,
            status=TimetableStatus.PROCESSING,
            revision_number=new_rev_number,
            title=title,
            change_summary=change_summary,
            schedule_data={},           # populated by Celery task
            is_active=False,            # goes True once task completes
            uploaded_by=user,
        )
        # Point the image field at the object that is already in the bucket.
        timetable.source_image.name = storage_path
        timetable.save(update_fields=['source_image'])

        logger.info(
            '[TIMETABLE] Record created (id=%s, rev=%s) from direct upload — dispatching Celery task.',
            timetable.id, new_rev_number,
        )

        transaction.on_commit(lambda: process_timetable_image_task.apply_async(
            args=[timetable.id], queue='docs_queue',
        ))

        return timetable

    @staticmethod
    def mutate_timetable_slot(
        timetable: ProgrammeTimetable,
        action: str,  # 'add', 'update', 'delete'
        slot_data: Optional[Dict[str, Any]] = None,
        slot_id: Optional[str] = None,
        user=None,
    ) -> ProgrammeTimetable:
        """
        Safely update, add, or delete an individual slot in the timetable schedule
        and automatically recompute free study slots.
        """
        schedule_data = timetable.schedule_data or {}
        weekly_schedule = list(schedule_data.get('weekly_schedule', []))

        if action == 'delete' and slot_id:
            weekly_schedule = [s for s in weekly_schedule if str(s.get('id')) != str(slot_id)]

        elif action == 'add' and slot_data:
            day = str(slot_data.get('day', 'Monday')).capitalize()
            start_t = str(slot_data.get('start_time', '08:00')).strip()
            unit_c = str(slot_data.get('unit_code', 'UNIT')).strip()
            gen_id = slot_data.get('id') or f"{day[:3].lower()}_{start_t.replace(':', '')}_{unit_c.replace(' ', '').lower()}"

            new_slot = {
                'id': gen_id,
                'day': day,
                'day_index': DAY_INDEX_MAP.get(day.lower(), 1),
                'start_time': start_t,
                'end_time': str(slot_data.get('end_time', '11:00')).strip(),
                'unit_code': unit_c,
                'unit_name': str(slot_data.get('unit_name', '')).strip(),
                'venue': str(slot_data.get('venue', '')).strip(),
                'lecturer': str(slot_data.get('lecturer', '')).strip(),
                'session_type': str(slot_data.get('session_type', 'Lecture')).strip(),
            }
            weekly_schedule.append(new_slot)

        elif action == 'update' and slot_data:
            target_id = str(slot_data.get('id') or slot_id or '')
            day = str(slot_data.get('day', '')).capitalize()
            for idx, s in enumerate(weekly_schedule):
                if str(s.get('id')) == target_id:
                    weekly_schedule[idx] = {
                        'id': target_id,
                        'day': day or s.get('day', 'Monday'),
                        'day_index': DAY_INDEX_MAP.get((day or s.get('day', 'Monday')).lower(), 1),
                        'start_time': str(slot_data.get('start_time', s.get('start_time', '08:00'))).strip(),
                        'end_time': str(slot_data.get('end_time', s.get('end_time', '11:00'))).strip(),
                        'unit_code': str(slot_data.get('unit_code', s.get('unit_code', ''))).strip(),
                        'unit_name': str(slot_data.get('unit_name', s.get('unit_name', ''))).strip(),
                        'venue': str(slot_data.get('venue', s.get('venue', ''))).strip(),
                        'lecturer': str(slot_data.get('lecturer', s.get('lecturer', ''))).strip(),
                        'session_type': str(slot_data.get('session_type', s.get('session_type', 'Lecture'))).strip(),
                    }
                    break

        # Re-sort weekly schedule by day_index then start_time
        weekly_schedule.sort(key=lambda s: (s.get('day_index', 1), s.get('start_time', '00:00')))

        # Recompute free slots
        schedule_data['weekly_schedule'] = weekly_schedule
        schedule_data['free_slots'] = compute_free_slots(weekly_schedule)

        timetable.schedule_data = schedule_data
        if user:
            timetable.verified_by = user
        timetable.save(update_fields=['schedule_data', 'verified_by', 'updated_at'])
        return timetable
